-- =====================================================================
-- IF Agora - schema.sql
-- Banco: H2 (em memória, o padrão do projeto) - SQL compatível com PostgreSQL.
-- Executado automaticamente pelo Spring Boot ANTES do data.sql.
--
-- Legenda de prioridade (MoSCoW do workshop):
--   [M] = Must Have (núcleo do MVP de 12 semanas)
--   [S] = Should Have (entra se sobrar tempo)
--
-- Convenções (para o Spring Data JDBC mapear sem anotações extras):
--   * tabela no singular e em snake_case: Aviso -> aviso, RelatoFila -> relato_fila
--   * chave primária sempre "id" (BIGINT, identity)
--   * campos snake_case: criadoEm -> criado_em
--   * enums gravados como texto (VARCHAR) com CHECK listando os valores
-- =====================================================================

-- Limpeza (ordem inversa das dependências) para poder rodar de novo.
DROP TABLE IF EXISTS relato_fila;
DROP TABLE IF EXISTS cardapio;
DROP TABLE IF EXISTS horario_aula;
DROP TABLE IF EXISTS relato_acessibilidade;
DROP TABLE IF EXISTS confirmacao_aviso;
DROP TABLE IF EXISTS notificacao;
DROP TABLE IF EXISTS dispositivo;
DROP TABLE IF EXISTS aviso;
DROP TABLE IF EXISTS espaco;
DROP TABLE IF EXISTS usuario;
DROP TABLE IF EXISTS turma;
DROP TABLE IF EXISTS curso;
DROP TABLE IF EXISTS campus;

-- ---------------------------------------------------------------------
-- [M] campus: cada unidade do IFTM
-- ---------------------------------------------------------------------
CREATE TABLE campus (
    id      BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome    VARCHAR(100) NOT NULL,
    cidade  VARCHAR(100) NOT NULL,
    ativo   BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_campus_nome UNIQUE (nome)
);

-- ---------------------------------------------------------------------
-- [M] curso: pertence a um campus
-- ---------------------------------------------------------------------
CREATE TABLE curso (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campus_id  BIGINT       NOT NULL,
    nome       VARCHAR(150) NOT NULL,
    nivel      VARCHAR(30)  NOT NULL,
    CONSTRAINT fk_curso_campus FOREIGN KEY (campus_id) REFERENCES campus (id),
    CONSTRAINT uq_curso_campus_nome UNIQUE (campus_id, nome),
    CONSTRAINT ck_curso_nivel CHECK (nivel IN
        ('TECNICO_INTEGRADO', 'TECNICO_SUBSEQUENTE', 'GRADUACAO', 'POS_GRADUACAO'))
);

-- ---------------------------------------------------------------------
-- [M] turma: grupo de alunos de um curso em um ano letivo
-- ---------------------------------------------------------------------
CREATE TABLE turma (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    curso_id    BIGINT       NOT NULL,
    nome        VARCHAR(80)  NOT NULL,
    ano_letivo  INTEGER      NOT NULL,
    CONSTRAINT fk_turma_curso FOREIGN KEY (curso_id) REFERENCES curso (id),
    CONSTRAINT uq_turma_curso_nome_ano UNIQUE (curso_id, nome, ano_letivo),
    CONSTRAINT ck_turma_ano CHECK (ano_letivo BETWEEN 2000 AND 2100)
);

-- ---------------------------------------------------------------------
-- [M] usuario: aluno, professor, servidor ou administrador
-- Login = e-mail institucional. Guardar SEMPRE o hash (BCrypt), nunca a senha.
-- turma_id só faz sentido para aluno (por isso é opcional).
-- ---------------------------------------------------------------------
CREATE TABLE usuario (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campus_id   BIGINT       NOT NULL,
    turma_id    BIGINT,
    nome        VARCHAR(150) NOT NULL,
    email       VARCHAR(150) NOT NULL,
    senha_hash  VARCHAR(100) NOT NULL,
    perfil      VARCHAR(20)  NOT NULL,
    ativo       BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_usuario_campus FOREIGN KEY (campus_id) REFERENCES campus (id),
    CONSTRAINT fk_usuario_turma  FOREIGN KEY (turma_id)  REFERENCES turma (id),
    CONSTRAINT uq_usuario_email  UNIQUE (email),
    CONSTRAINT ck_usuario_perfil CHECK (perfil IN ('ALUNO', 'PROFESSOR', 'SERVIDOR', 'ADMIN')),
    CONSTRAINT ck_usuario_turma_aluno CHECK (turma_id IS NULL OR perfil = 'ALUNO')
);

-- ---------------------------------------------------------------------
-- [M] espaco: sala, laboratório, refeitório, elevador, rampa etc.
-- Serve tanto para "sala trocada" nos avisos quanto para os relatos
-- de acessibilidade.
-- ---------------------------------------------------------------------
CREATE TABLE espaco (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campus_id  BIGINT       NOT NULL,
    nome       VARCHAR(100) NOT NULL,
    bloco      VARCHAR(50),
    tipo       VARCHAR(20)  NOT NULL,
    acessivel  BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_espaco_campus FOREIGN KEY (campus_id) REFERENCES campus (id),
    CONSTRAINT uq_espaco_campus_nome UNIQUE (campus_id, nome),
    CONSTRAINT ck_espaco_tipo CHECK (tipo IN
        ('SALA', 'LABORATORIO', 'BIBLIOTECA', 'REFEITORIO', 'BANHEIRO',
         'ELEVADOR', 'RAMPA', 'QUADRA', 'OUTRO'))
);

-- ---------------------------------------------------------------------
-- [M] aviso: o núcleo do app (aula cancelada, sala trocada...)
-- turma_id NULL = aviso para o campus inteiro.
-- Feed da turma T do campus C:
--   WHERE ativo AND campus_id = C AND (turma_id IS NULL OR turma_id = T)
-- ---------------------------------------------------------------------
CREATE TABLE aviso (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campus_id  BIGINT       NOT NULL,
    turma_id   BIGINT,
    autor_id   BIGINT       NOT NULL,
    espaco_id  BIGINT,
    tipo       VARCHAR(20)  NOT NULL,
    titulo     VARCHAR(150) NOT NULL,
    descricao  VARCHAR(1000),
    criado_em  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expira_em  TIMESTAMP,
    ativo      BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_aviso_campus FOREIGN KEY (campus_id) REFERENCES campus (id),
    CONSTRAINT fk_aviso_turma  FOREIGN KEY (turma_id)  REFERENCES turma (id),
    CONSTRAINT fk_aviso_autor  FOREIGN KEY (autor_id)  REFERENCES usuario (id),
    CONSTRAINT fk_aviso_espaco FOREIGN KEY (espaco_id) REFERENCES espaco (id),
    CONSTRAINT ck_aviso_tipo CHECK (tipo IN
        ('AULA_CANCELADA', 'SALA_TROCADA', 'AULA_VAGA', 'ATRASO', 'COMUNICADO')),
    CONSTRAINT ck_aviso_validade CHECK (expira_em IS NULL OR expira_em > criado_em)
);
CREATE INDEX idx_aviso_feed ON aviso (campus_id, turma_id, criado_em);

-- ---------------------------------------------------------------------
-- [M] dispositivo: token de push (Firebase Cloud Messaging) de cada celular
-- ---------------------------------------------------------------------
CREATE TABLE dispositivo (
    id          BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT        NOT NULL,
    token_push  VARCHAR(500)  NOT NULL,
    plataforma  VARCHAR(10)   NOT NULL,
    criado_em   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_dispositivo_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT uq_dispositivo_token UNIQUE (token_push),
    CONSTRAINT ck_dispositivo_plataforma CHECK (plataforma IN ('ANDROID', 'IOS', 'WEB'))
);

-- ---------------------------------------------------------------------
-- [M] notificacao: registro de quem foi avisado de quê (e se já leu)
-- ---------------------------------------------------------------------
CREATE TABLE notificacao (
    id          BIGINT     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT     NOT NULL,
    aviso_id    BIGINT     NOT NULL,
    enviada_em  TIMESTAMP  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    lida        BOOLEAN    NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_notificacao_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT fk_notificacao_aviso   FOREIGN KEY (aviso_id)   REFERENCES aviso (id),
    CONSTRAINT uq_notificacao_usuario_aviso UNIQUE (usuario_id, aviso_id)
);

-- ---------------------------------------------------------------------
-- [S] confirmacao_aviso: "eu confirmo" - um voto por usuário por aviso
-- ---------------------------------------------------------------------
CREATE TABLE confirmacao_aviso (
    id          BIGINT     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aviso_id    BIGINT     NOT NULL,
    usuario_id  BIGINT     NOT NULL,
    criado_em   TIMESTAMP  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_confirmacao_aviso   FOREIGN KEY (aviso_id)   REFERENCES aviso (id),
    CONSTRAINT fk_confirmacao_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT uq_confirmacao_aviso_usuario UNIQUE (aviso_id, usuario_id)
);

-- ---------------------------------------------------------------------
-- [S] relato_acessibilidade: elevador quebrado, rampa bloqueada etc.
-- Se o status for RESOLVIDO, resolvido_em é obrigatório.
-- ---------------------------------------------------------------------
CREATE TABLE relato_acessibilidade (
    id           BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    espaco_id    BIGINT        NOT NULL,
    usuario_id   BIGINT        NOT NULL,
    tipo         VARCHAR(30)   NOT NULL,
    descricao    VARCHAR(500),
    status       VARCHAR(15)   NOT NULL DEFAULT 'ABERTO',
    criado_em    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolvido_em TIMESTAMP,
    CONSTRAINT fk_relato_acess_espaco  FOREIGN KEY (espaco_id)  REFERENCES espaco (id),
    CONSTRAINT fk_relato_acess_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT ck_relato_acess_tipo CHECK (tipo IN
        ('ELEVADOR_QUEBRADO', 'RAMPA_BLOQUEADA', 'PISO_TATIL_DANIFICADO',
         'BANHEIRO_INDISPONIVEL', 'OUTRO')),
    CONSTRAINT ck_relato_acess_status CHECK (status IN ('ABERTO', 'EM_ANALISE', 'RESOLVIDO')),
    CONSTRAINT ck_relato_acess_resolucao CHECK (status <> 'RESOLVIDO' OR resolvido_em IS NOT NULL)
);

-- ---------------------------------------------------------------------
-- [S] horario_aula: base da tela "próxima aula e sala"
-- dia_semana segue o padrão ISO: 1 = segunda ... 7 = domingo
-- ---------------------------------------------------------------------
CREATE TABLE horario_aula (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    turma_id      BIGINT       NOT NULL,
    espaco_id     BIGINT       NOT NULL,
    professor_id  BIGINT,
    disciplina    VARCHAR(120) NOT NULL,
    dia_semana    SMALLINT     NOT NULL,
    hora_inicio   TIME         NOT NULL,
    hora_fim      TIME         NOT NULL,
    CONSTRAINT fk_horario_turma     FOREIGN KEY (turma_id)     REFERENCES turma (id),
    CONSTRAINT fk_horario_espaco    FOREIGN KEY (espaco_id)    REFERENCES espaco (id),
    CONSTRAINT fk_horario_professor FOREIGN KEY (professor_id) REFERENCES usuario (id),
    CONSTRAINT ck_horario_dia  CHECK (dia_semana BETWEEN 1 AND 7),
    CONSTRAINT ck_horario_hora CHECK (hora_fim > hora_inicio)
);
CREATE INDEX idx_horario_turma_dia ON horario_aula (turma_id, dia_semana, hora_inicio);

-- ---------------------------------------------------------------------
-- [S] cardapio: o que tem em cada refeição, por campus e dia
-- ---------------------------------------------------------------------
CREATE TABLE cardapio (
    id            BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campus_id     BIGINT        NOT NULL,
    data_refeicao DATE          NOT NULL,
    refeicao      VARCHAR(10)   NOT NULL,
    descricao     VARCHAR(500)  NOT NULL,
    CONSTRAINT fk_cardapio_campus FOREIGN KEY (campus_id) REFERENCES campus (id),
    CONSTRAINT uq_cardapio_dia_refeicao UNIQUE (campus_id, data_refeicao, refeicao),
    CONSTRAINT ck_cardapio_refeicao CHECK (refeicao IN ('CAFE', 'ALMOCO', 'JANTAR'))
);

-- ---------------------------------------------------------------------
-- [S] relato_fila: aluno informa se a fila do refeitório está grande
-- ---------------------------------------------------------------------
CREATE TABLE relato_fila (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campus_id   BIGINT       NOT NULL,
    usuario_id  BIGINT       NOT NULL,
    nivel       VARCHAR(10)  NOT NULL,
    criado_em   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_relato_fila_campus  FOREIGN KEY (campus_id)  REFERENCES campus (id),
    CONSTRAINT fk_relato_fila_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT ck_relato_fila_nivel CHECK (nivel IN ('POUCA', 'MEDIA', 'GRANDE'))
);
CREATE INDEX idx_relato_fila_recente ON relato_fila (campus_id, criado_em);
